    def run_hydro(self) -> None:
        """Execute the HYDRO++/PRO executable on the selected files with live output and progress."""
        if not self.struct_files:
            QMessageBox.warning(self, "No files", "Please select one or more files first.")
            return
        exe_path = self._ensure_executable_available()
        if not exe_path:
            QMessageBox.information(self, "Executable required", "Please configure the HYDRO executable before running.")
            return

        total = len(self.struct_files)
        base_work_dir = Path.home() / '.hydropp_gui'
        base_work_dir.mkdir(exist_ok=True)

        # Show output/progress dialog
        out_dlg = OutputDialog(self, total_steps=total)
        out_dlg.set_status(f"Starting HYDRO for {total} file(s)…")
        out_dlg.append(f"Executable: {exe_path}")
        out_dlg.show()
        QApplication.processEvents()

        self.results = []
        for idx, struct_file in enumerate(self.struct_files, start=1):
            if out_dlg.canceled:
                break
            job_dir = base_work_dir / f"job_{idx:03d}"
            job_dir.mkdir(parents=True, exist_ok=True)

            # Determine executable type
            is_hydropro = 'hydropro' in exe_path.name.lower()

            if is_hydropro:
                # HYDROPRO expects hydropro.dat and the structural file accessible in CWD
                job_struct = job_dir / struct_file.name
                try:
                    shutil.copyfile(str(struct_file), str(job_struct))
                    out_dlg.append(f"Copied structure file to job folder: {job_struct}")
                except Exception as ex:
                    out_dlg.append(f"ERROR: failed to copy structure file: {ex}")
                generic, hp_input = write_hydropro_input(job_struct, job_dir, self.hp_settings)
                out_dlg.append(f"Generated hydropro.dat: {hp_input} (Generic base: {generic})")
                input_to_feed = hp_input.name
                base_name_for_results = generic
                expected_res_path = job_dir / f"{generic}-res.txt"
            else:
                # HYDRO++ style input
                input_file = job_dir / 'hydro_input.dat'
                basenames = construct_input_file([struct_file], input_file)
                basename = basenames[0] if basenames else "case001"
                input_to_feed = input_file.name
                base_name_for_results = basename
                expected_res_path = job_dir / f"{basename}-res.txt"

            try:
                cmd = [str(exe_path)]
                out_dlg.set_status(f"[{idx}/{total}] Running {struct_file.name}…")
                out_dlg.append(f"\n=== Job {idx}/{total}: {struct_file} ===")
                out_dlg.append(f"Working directory: {job_dir}")
                QApplication.processEvents()

                process = subprocess.Popen(
                    cmd,
                    stdin=subprocess.PIPE,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    cwd=str(job_dir),
                )
                out_bytes, err_bytes = process.communicate(input=f"{input_to_feed}\n".encode('utf-8'), timeout=300)
                out_text = out_bytes.decode('utf-8', errors='ignore') if out_bytes else ''
                err_text = err_bytes.decode('utf-8', errors='ignore') if err_bytes else ''

                if out_text.strip():
                    out_dlg.append(out_text.strip())
                if err_text.strip():
                    out_dlg.append("\n[STDERR]\n" + err_text.strip())
            except FileNotFoundError:
                QMessageBox.critical(self, "Execution error", "Failed to launch the external program.")
                out_dlg.append("ERROR: Executable not found.")
                break
            except subprocess.TimeoutExpired:
                process.kill()
                QMessageBox.critical(self, "Timeout", f"The HYDRO calculation for {struct_file.name} timed out.")
                out_dlg.append("ERROR: Timeout.")
                break

            # Parse result for this job
            res_path = expected_res_path
            coeff = parse_diffusion_coefficient(res_path)
            self.results.append((str(struct_file), coeff))
            if coeff is not None:
                out_dlg.append(f"Result: diffusion coefficient = {coeff:.3e} cm^2/s")
            else:
                out_dlg.append("Result: diffusion coefficient not found (see output above)")

            out_dlg.set_progress(idx)
            QApplication.processEvents()

            if out_dlg.canceled:
                out_dlg.append("\nCancelled by user.")
                break

        out_dlg.set_status("Finished.")
        out_dlg.cancel_btn.setEnabled(False)

        self.save_button.setEnabled(bool(self.results))
        self.update_table()

    def save_csv(self) -> None:
        """Save the current results table to a CSV file."""
        if not self.results:
            QMessageBox.warning(self, "No results", "There are no results to save.")
            return
        path, _ = QFileDialog.getSaveFileName(
            self,
            "Save CSV",
            str(Path.home() / "hydro_results.csv"),
            "CSV files (*.csv)"
        )
        if not path:
            return
        try:
            with open(path, 'w', newline='', encoding='utf-8') as csvfile:
                writer = csv.writer(csvfile)
                writer.writerow(["File", "DiffusionCoefficient(cm^2/s)"])
                for file_name, value in self.results:
                    writer.writerow([file_name, f"{value:.3e}" if value is not None else ""])
            QMessageBox.information(self, "Saved", f"Results saved to {path}")
        except Exception as exc:
            QMessageBox.critical(self, "Error", f"Failed to save CSV: {exc}")

    def clear_all(self) -> None:
        """Clear the table and cleanup the computation folder (.hydropp_gui)."""
        # Reset selections and results
        self.struct_files = []
        self.results = []
        self.update_table()
        # Disable actions until new files are selected/run
        self.run_button.setEnabled(False)
        self.save_button.setEnabled(False)
        # Remove computation folder recursively
        base_work_dir = Path.home() / '.hydropp_gui'
        try:
            if base_work_dir.exists():
                shutil.rmtree(str(base_work_dir), ignore_errors=False)
        except Exception:
            # Ensure best-effort cleanup
            try:
                shutil.rmtree(str(base_work_dir), ignore_errors=True)
            except Exception:
                pass
        # Recreate empty folder to keep workflow consistent
        try:
            base_work_dir.mkdir(exist_ok=True)
        except Exception:
            pass
        # Minimal user feedback
        QMessageBox.information(self, "Cleared", "Cleared the table and cleaned the computation folder.")

    def open_settings(self) -> None:
        """Open the Settings dialog to configure the HYDRO executable and HYDROPRO parameters."""
        dlg = SettingsDialog(current_exe=self.hydro_exe, current_settings=self.hp_settings, parent=self)
        if dlg.exec_() == QDialog.Accepted:
            # Update executable path if valid
            new_text = dlg.path_edit.text().strip()
            if new_text:
                new_path = Path(new_text)
                if new_path.exists() and new_path.is_file():
                    self._set_hydro_exe(new_path)
                else:
                    QMessageBox.warning(self, "Invalid path", f"The selected executable does not exist:\n{new_path}")
            # Update HYDROPRO settings
            if getattr(dlg, 'result_settings', None) is not None:
                self.hp_settings = dlg.result_settings
            self._save_settings()
            QMessageBox.information(self, "Settings", "Settings updated.")

    def open_download_page(self) -> None:
        """Open the HYDRO++/PRO download page specified in the URL field."""
        url_str = self.url_edit.text().strip()
        if not url_str:
            QMessageBox.warning(self, "No URL", "Please enter a valid URL.")
            return
        QDesktopServices.openUrl(QUrl(url_str))


