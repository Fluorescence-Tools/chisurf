def parse_diffusion_coefficient(res_path: Path) -> Optional[float]:
    """Extract the translational diffusion coefficient from a HYDRO++/PRO
    ``*.res`` file.

    The report files generated by HYDROPRO and HYDRO++ contain a
    human‑readable summary section where the translational diffusion
    coefficient is reported as a number in cm^2/s.  For example, a
    HYDRO++ result file may contain a line like::

        Translational diffusion coefficient:  3.760E-07 cm^2/s

    This function scans the file for the first occurrence of the phrase
    ``diffusion coefficient`` and returns the numeric value as a float.

    Parameters
    ----------
    res_path: Path
        Path to the ``*.res`` file.

    Returns
    -------
    float or None
        The extracted diffusion coefficient, or ``None`` if it could not be
        found or converted.
    """
    # Case‑insensitive search for the diffusion coefficient using scientific
    # notation (e.g. 3.760E-07).  We deliberately capture only the numeric
    # portion; units are ignored.
    pattern = re.compile(r"(?i)diffusion\s+coefficient\s*:\s*([-+]?\d*\.\d+E[-+]?\d+|[-+]?\d+\.\d+|[-+]?\d+)")
    try:
        with res_path.open('r', encoding='utf-8', errors='ignore') as f:
            for line in f:
                match = pattern.search(line)
                if match:
                    try:
                        value_str = match.group(1)
                        return float(value_str)
                    except ValueError:
                        continue
    except FileNotFoundError:
        return None
    return None


def construct_input_file(struct_files: List[Path], input_path: Path) -> List[str]:
    """Create a HYDRO++/PRO main input file for the given structural files.

    This helper writes a simple input file containing one block per structure.
    Each block provides placeholder hydrodynamic parameters that can be
    adjusted to reflect typical laboratory conditions【434851143996887†L120-L168】.  The structural file
    name is taken directly from ``struct_files``.  The resulting input file
    will be saved to ``input_path`` and a list of expected output basenames
    (without extensions) is returned.

    Parameters
    ----------
    struct_files: list of Path
        List of structural files to include.  These may be PDB files or
        coordinate files in the bead format expected by HYDRO++/PRO.

    input_path: Path
        Path where the input file will be written.

    Returns
    -------
    List[str]
        A list of base filenames (without extension) that will be used for
        the output files.  HYDRO++/PRO appends extensions such as ``.res``.
    """
    output_basenames: List[str] = []
    lines: List[str] = []
    for idx, struct_file in enumerate(struct_files, start=1):
        title = struct_file.stem[:20].ljust(20)  # up to 20 characters for TITLE
        basename = f"case{idx:03d}"
        output_basenames.append(basename)
        # A block of parameters; see Section 3 of the HYDRO++ user guide【434851143996887†L120-L168】.
        block = [
            title,
            basename.ljust(30),
            str(struct_file).ljust(30),
            "12",  # ICASE (12 = recommended option for HYDRO++)
            "20.0",  # Temperature (°C)
            "0.010",  # Solvent viscosity (poise)
            "100000.0",  # Molecular weight (Da); default placeholder
            "0.74",  # Partial specific volume (cm^3/g); typical for proteins
            "1.0",  # Solution density (g/cm^3)
            "0",  # NQ: number of scattering angles; 0 disables scattering calculations
            "0.0",  # HMAX; unused when NQ=0
            "0",  # Number of intervals for distance distribution
            "0.0",  # RMAX; unused when intervals=0
            "0",  # NTRIALS; unused when scattering/covolume is disabled
            "1",  # IDIF=1; compute full diffusion tensors
        ]
        lines.extend(block)
    lines.append('*')  # End of file marker
    input_content = '\n'.join(lines)
    input_path.write_text(input_content)
    return output_basenames


def write_hydropro_input(struct_file: Path, job_dir: Path, settings: 'HydroProSettings') -> Tuple[str, Path]:
    """Create a HYDROPRO-compatible hydropro.dat for a single structure using settings.

    Returns a tuple (generic_basename, input_path).
    The structural file is assumed to be located in job_dir (relative path used).
    """
    generic = struct_file.stem  # base for output files
    title = (generic[:28] + "…") if len(generic) > 28 else generic

    lines: List[str] = []
    # First part: structure and primary model
    lines.append(f"{title}                        !TITLE (CHAR*20)")
    lines.append(f"{generic}                        !FILENAME (base for outputs)")
    lines.append(f"{struct_file.name}        !INPUT PDB filename (relative)")
    lines.append(f"{settings.indmode}               !INDMODE: 1 atomic/shell, 2 residue/shell, 4 residue/bead")
    lines.append(f"{settings.aer},            !AER (Å) hydrodynamic radius of primary elements")
    if settings.indmode in (1, 2):
        # Shell model needs NSIG and optionally SIGMIN/SIGMAX
        if settings.nsig == -1:
            lines.append(f"-1,              !NSIG=-1 for automatic sigma range")
        else:
            lines.append(f"{int(settings.nsig)},              !NSIG (>=3 typical 5-8)")
            lines.append(f"{settings.sigmin},            !SIGMIN (Å) minibead radius")
            lines.append(f"{settings.sigmax},            !SIGMAX (Å) minibead radius")
    # Second part: macromolecule and solvent properties
    lines.append(f"{settings.t},            !T (°C)")
    lines.append(f"{settings.eta},           !ETA (poise)")
    lines.append(f"{settings.rm},        !RM (Da)")
    lines.append(f"{settings.vbar},           !VBAR (cm3/g)")
    lines.append(f"{settings.rho},            !RHO (g/cm3)")
    # Third part: optional calculations
    lines.append(f"{int(settings.nq)}              !NQ: 0 omit, -1 automatic, >0 specify QMAX")
    if settings.nq and settings.nq > 0:
        lines.append(f"{settings.qmax}              !QMAX (cm^-1)")
    lines.append(f"{int(settings.ns)}              !NS: 0 omit, -1 automatic, >0 specify RMAX")
    if settings.ns and settings.ns > 0:
        lines.append(f"{settings.rmax}              !RMAX (cm)")
    lines.append(f"{int(settings.ntrials)},              !NTRIALS for covolume (MC)")
    lines.append(f"{int(settings.idif)}               !IDIF=1 for full diffusion tensors")
    lines.append("*                                    !End of file")

    input_path = job_dir / 'hydropro.dat'
    input_path.write_text("\n".join(lines))
    return generic, input_path


@dataclass
class HydroProSettings:
    indmode: int = 1            # 1 atomic/shell, 2 residue/shell, 4 residue/bead
    aer: float = 2.9            # AER per manual (Å)
    nsig: int = 6               # number of sigma values; -1 for automatic
    sigmin: float = 1.0         # only when nsig != -1
    sigmax: float = 2.0         # only when nsig != -1
    t: float = 20.0             # temperature (°C)
    eta: float = 0.01           # solvent viscosity (poise)
    rm: float = 100000.0        # molecular weight (Da)
    vbar: float = 0.74          # partial specific volume (cm^3/g)
    rho: float = 1.0            # solution density (g/cm^3)
    nq: int = -1                # scattering values; 0 omit, -1 automatic, >0 provide qmax
    qmax: float = 0.0           # only when nq > 0
    ns: int = -1                # distance distribution intervals; 0 omit, -1 automatic, >0 provide rmax
    rmax: float = 0.0           # only when ns > 0
    ntrials: int = 0            # Monte Carlo covolume trials
    idif: int = 1               # 1 to output full diffusion tensors


class OutputDialog(QDialog):
    """Simple dialog to display CLI output and a progress bar."""
    def __init__(self, parent=None, total_steps: int = 0):
        super().__init__(parent)
        self.setWindowTitle("HYDRO Output")
        self.resize(900, 600)
        self.canceled = False

        self.status_label = QLabel("Ready")
        self.progress = QProgressBar()
        self.progress.setRange(0, total_steps)
        self.progress.setValue(0)
        self.log = QPlainTextEdit()
        self.log.setReadOnly(True)

        # Buttons
        self.clear_btn = QPushButton("Clear")
        self.save_btn = QPushButton("Save Log…")
        self.cancel_btn = QPushButton("Cancel")

        self.clear_btn.clicked.connect(self.log.clear)
        self.save_btn.clicked.connect(self._save_log)
        self.cancel_btn.clicked.connect(self._on_cancel)

        # Layout
        layout = QVBoxLayout(self)
        layout.addWidget(self.status_label)
        layout.addWidget(self.progress)
        layout.addWidget(self.log)

        btn_row = QHBoxLayout()
        btn_row.addWidget(self.clear_btn)
        btn_row.addStretch(1)
        btn_row.addWidget(self.save_btn)
        btn_row.addWidget(self.cancel_btn)
        layout.addLayout(btn_row)

    def _on_cancel(self) -> None:
        self.canceled = True
        self.cancel_btn.setEnabled(False)
        self.status_label.setText("Cancelling after current job finishes…")

    def _save_log(self) -> None:
        path, _ = QFileDialog.getSaveFileName(self, "Save output log", str(Path.home() / "hydro_output.txt"), "Text files (*.txt)")
        if path:
            try:
                with open(path, 'w', encoding='utf-8') as f:
                    f.write(self.log.toPlainText())
            except Exception:
                pass

    def set_status(self, text: str) -> None:
        self.status_label.setText(text)

    def set_progress(self, value: int) -> None:
        self.progress.setValue(value)

    def append(self, text: str) -> None:
        self.log.appendPlainText(text)
        # Auto-scroll to bottom
        self.log.moveCursor(QTextCursor.End)


