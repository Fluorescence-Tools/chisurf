"""
Hydro++/HydroPRO GUI
====================

This module implements a simple graphical interface around the command-line
programs **HYDROPRO** and **HYDRO++**.  Both programs belong to the HYDRO
software suite created by J. García de la Torre and colleagues and are used
to compute hydrodynamic and other solution properties for bead models of
macromolecules.  The 2011 revision of HYDROPRO adds support for
coarse–grained residue‑level models and a graphical interface【804691996725103†L40-L52】,
while HYDRO++ improves the accuracy of rotational diffusion and intrinsic
viscosity calculations for bead models【434851143996887†L74-L82】.  A single run of either
program reads a *main input file* specifying one or more calculations and
writes human‑readable report files (``*.res``) that contain the translational
diffusion coefficient among other quantities.

The goal of this script is to make it easy to:

* Select one or more structural files (e.g. PDB or bead coordinate files).
* Assemble a minimal input file for the command‑line program.
* Run the external executable for each file and parse the resulting ``.res``
  reports for the translational diffusion coefficient.
* Present the results in a table and allow the user to export them to CSV.
* Provide a button to open the official download page for HYDRO++/HYDROPRO and
  an optional field for a user‑supplied alternative URL.
* Display a reference to the principal publication describing the HYDRO++
  algorithm【434851143996887†L74-L82】.

This implementation is intentionally conservative: it does not attempt to
interpret PDB files or build bead models on the fly.  Instead, it assumes
that the selected structural files are already in a format accepted by
HYDRO++/HYDROPRO (either a bead coordinate file as described in the
documentation or, for HYDROPRO, a PDB file).  The user is responsible for
providing appropriate files and verifying the results.  The program
constructs a simple input file for each case using default hydrodynamic
parameters; these may be adjusted in the code if necessary.
"""

