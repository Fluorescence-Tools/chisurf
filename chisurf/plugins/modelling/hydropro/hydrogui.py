    def _set_hydro_exe(self, path: Optional[Path]) -> None:
        self.hydro_exe = Path(path) if path else Path()

    def _load_settings(self) -> None:
        try:
            exe_str = self._qsettings.value("hydro_exe", "", type=str)
            self._set_hydro_exe(Path(exe_str) if exe_str else None)
            self.show_info_on_startup = bool(self._qsettings.value("show_info_on_startup", True, type=bool))
            # Load HP settings
            for f in fields(HydroProSettings):
                key = f"hp.{f.name}"
                default_val = getattr(self.hp_settings, f.name)
                val = self._qsettings.value(key, default_val)
                try:
                    if isinstance(default_val, int):
                        setattr(self.hp_settings, f.name, int(float(val)))
                    elif isinstance(default_val, float):
                        setattr(self.hp_settings, f.name, float(val))
                    elif isinstance(default_val, bool):
                        sval = str(val).strip().lower()
                        setattr(self.hp_settings, f.name, sval in ("1", "true", "yes", "on"))
                    else:
                        setattr(self.hp_settings, f.name, val)
                except Exception:
                    setattr(self.hp_settings, f.name, default_val)
        except Exception:
            pass

    def _save_settings(self) -> None:
        try:
            self._qsettings.setValue("hydro_exe", str(self.hydro_exe) if self.hydro_exe else "")
            self._qsettings.setValue("show_info_on_startup", self.show_info_on_startup)
            for f in fields(HydroProSettings):
                self._qsettings.setValue(f"hp.{f.name}", getattr(self.hp_settings, f.name))
        except Exception:
            pass

    def _maybe_show_download_info_on_startup(self) -> None:
        # Show dialog if no executable configured or missing
        if (not self.hydro_exe) or (not self.hydro_exe.exists()):
            if self.show_info_on_startup:
                self._show_download_info_dialog()

    def _show_download_info_dialog(self) -> None:
        url = self.url_edit.text().strip() if hasattr(self, 'url_edit') and self.url_edit.text().strip() else "https://leonardo.inf.um.es/macromol/programs/hydro%2B%2B/hydro%2B%2B.htm"
        dlg = DownloadInfoDialog(url, self)
        if dlg.exec_() == QDialog.Accepted:
            if dlg.selected_path and dlg.selected_path.exists():
                self._set_hydro_exe(dlg.selected_path)
            self.show_info_on_startup = not dlg.dont_show_startup
            self._save_settings()

    def _ensure_executable_available(self) -> Optional[Path]:
        if self.hydro_exe and self.hydro_exe.exists():
            return self.hydro_exe
        self._show_download_info_dialog()
        return self.hydro_exe if (self.hydro_exe and self.hydro_exe.exists()) else None

